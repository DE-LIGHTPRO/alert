// Generates fixtures/field-hash-vectors.json from web/hash.js — the hash the PAGE uses.
//
// WHY THE VECTORS COME FROM THE JAVASCRIPT.
//
// Three implementations truncate a keccak256 to 248 bits: the circuit, AlertHash.sol and
// the page. A disagreement between any two produces no error at all. The escrow stores a
// hash the proof can never match, and the settlement reverts with WrongAmount on an
// amount that is perfectly correct.
//
// So a Solidity test asserts these vectors (contracts/test/CrossLanguageHash.t.sol). The
// direction matters: generating them WITH Solidity and asserting them IN Solidity is a
// tautology that cannot fail, which is what contracts/script/Deploy.s.sol used to do with
// the bank domain. Generated here, asserted there, the test compares two languages.
//
// Usage:
//   npm ci && node scripts/gen-field-hash-vectors.mjs
//
// CI regenerates and fails on any diff, so neither side can drift alone.

import { writeFileSync, readFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = resolve(import.meta.dirname, "..");
const SRC = join(ROOT, "web", "hash.js");
const OUT = join(ROOT, "fixtures", "field-hash-vectors.json");

// The strings that actually cross the boundary. Anything the escrow stores a hash of, or
// the adapter compares a hash against, belongs here.
const INPUTS = [
  // the bank domain and the sender the adapter pins at construction
  "moniepoint.com",
  "no-reply@moniepoint.com",
  // amounts, with the thousands separators the bank's own template emits and the kobo tag
  // that makes each escrow's amount unique (CLAUDE.md rule 2)
  "160,000.98",
  // the five inputs AlertHash.t.sol pins as hand-written literals. Generating them here
  // too is what makes that file's cross-language claim true: its own vectors came from
  // `cast keccak`, which is Foundry's keccak and therefore the same implementation solc
  // uses, so they only ever confirmed Solidity against itself.
  "160,000.37",
  "5,000.00",
  "52988",
  "*****52988",
  "1,500.07",
  "25,000.00",
  "980,000.99",
  "7.01",
  // a masked recipient account, as the alert prints it
  "1234",
  "0001",
  // a MIME boundary, which is the nullifier: 60 characters, spans three field elements
  "----=_Part_1234567_1234567890.1234567890123--boundary-abcdef0",
  // adversarial shapes: the empty string, a single byte, exactly 31 and exactly 32 bytes,
  // and non-ASCII, because a UTF-8 encoding disagreement is invisible in the common case
  "",
  "a",
  "0123456789012345678901234567890",
  "01234567890123456789012345678901",
  "₦160,000.98",
  "Adébáyò",
];

// web/hash.js imports viem from esm.sh so the browser needs no build step. Node cannot
// resolve an https specifier, so rewrite that one line to a bare specifier and load the
// copy from inside the project, where node_modules resolves up the tree. The file is
// copied rather than edited: a generator that mutates the module it is measuring would be
// one interrupted run away from committing a rewritten page.
const localCopy = join(ROOT, ".hash.generated.mjs");
let failed = null;
try {
  const src = readFileSync(SRC, "utf8");
  const rewritten = src.replace(/"https:\/\/esm\.sh\/viem@[^"]+"/, '"viem"');
  if (rewritten === src) {
    throw new Error(`no esm.sh viem import found in ${SRC} — has the import style changed?`);
  }
  writeFileSync(localCopy, rewritten);

  const { fieldHash, FIELD_MASK } = await import(pathToFileURL(localCopy).href);

  if (FIELD_MASK !== (1n << 248n) - 1n) {
    throw new Error(`web/hash.js FIELD_MASK is ${FIELD_MASK}, expected 2^248 - 1`);
  }

  const hashes = INPUTS.map((input) => {
    const hash = fieldHash(input);
    // A mask that silently did nothing would still produce 32 bytes. Assert the top byte
    // is clear, which is the whole point of the truncation.
    if (BigInt(hash) > FIELD_MASK) {
      throw new Error(`fieldHash(${JSON.stringify(input)}) exceeds the field mask`);
    }
    return hash;
  });

  // Parallel arrays rather than an array of {input, hash} objects: forge's
  // parseJson*Array takes one path and rejects a wildcard, and decoding into a struct
  // array orders the fields alphabetically against the JSON keys, which silently puts
  // the hash where the input belongs. Two flat arrays have neither failure mode, and the
  // test asserts the lengths agree.
  const payload = {
    _note:
      "Generated by scripts/gen-field-hash-vectors.mjs from web/hash.js. " +
      "Asserted by contracts/test/CrossLanguageHash.t.sol. inputs[i] hashes to " +
      "hashes[i]. Do not hand-edit.",
    viem: "2.21.54",
    fieldMask: `0x${((1n << 248n) - 1n).toString(16)}`,
    inputs: INPUTS,
    hashes,
  };
  writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`wrote ${hashes.length} vectors to fixtures/field-hash-vectors.json`);
} catch (e) {
  failed = e;
} finally {
  rmSync(localCopy, { force: true });
}
if (failed) {
  console.error(failed.message);
  process.exit(1);
}
